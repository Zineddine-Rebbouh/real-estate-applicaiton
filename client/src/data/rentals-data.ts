export type PropertyType =
  | "Apartment"
  | "House"
  | "Condo"
  | "Townhouse"
  | "Studio"
  | "Loft";

export type BadgeItem = {
  label: string;
  variant: "success" | "outline" | "secondary" | "default";
  iconName?: "pet" | "car" | "sparkles" | "badge-check" | "sun" | "shield";
};

export type RentalProperty = {
  id: string;
  title: string;
  address: string;
  neighborhood: string;
  city: string;
  price: number;
  beds: number; // 0 for Studio
  baths: number;
  sqft: number;
  propertyType: PropertyType;
  image: string;
  gallery: string[];
  badges: BadgeItem[];
  rating: number;
  reviewCount: number;
  // Normalized percentage coordinates (0-100) for the interactive vector basemap
  coords: {
    x: number;
    y: number;
    lat: number;
    lng: number;
  };
  amenities: string[];
  petFriendly: boolean;
  parkingIncluded: boolean;
  isFavorite?: boolean;
  featured?: boolean;
  availableDate: string;
};

